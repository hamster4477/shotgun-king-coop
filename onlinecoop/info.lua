description=[=[The Black King has a shotgun. His last loyal Knight has a blade. Play through Throne, Endless or Charnier together, with new cards that reward fighting side by side and hidden endings to discover.

[b]On one PC[/b]
Subscribe, enable this mod, and choose a local Co-op mode under Play. If you have the old standalone co-op mod installed, disable it first.

[b]On two Windows PCs · First-time setup[/b]
1. Both players subscribe to this item. Once Steam finishes downloading it, close the game.
2. In the Steam library where Shotgun King is installed, open [b]steamapps/workshop/content/1972440/3833493529[/b].
3. On each PC, run [b]Configure Steam Launch.vbs[/b], select the Steam account you play on, then click [b]Apply and restart Steam[/b]. After that, launch Shotgun King from Steam as usual.

[b]Host and join[/b]
Both PCs must be able to reach each other. Use the same LAN, join the same virtual LAN, or have the host set up a TCP tunnel. Both players open Play and select the same LAN mode. For Throne, choose [b]LAN Co-op[/b].

[b]Host (Black King):[/b] If several addresses appear, select the one your friend can reach. Click [b]Create room[/b], then [b]Copy invite[/b], and send the whole code to your friend.
[b]Guest (Black Knight):[/b] Copy the code, click [b]Paste[/b] beside the input field, then [b]Join[/b]. Once connected, the host chooses a weapon and rank and starts the run.

[b]Using a TCP tunnel?[/b] The host forwards the tunnel to the local address and port shown in the lobby, then enters the public address and port in the lobby’s optional tunnel settings before creating the room. The guest joins with the invite code as usual.

