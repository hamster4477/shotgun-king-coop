[b]同一台电脑玩[/b]
订阅并启用本模组，在「游玩」里选择本地合作模式即可。如果装过旧版独立合作模组，请先停用旧版。

[b]两台 Windows 电脑联机 · 首次设置[/b]
1. 两个人都订阅本条目，等 Steam 下载完成后退出游戏。
2. 打开安装《霰弹国王》的 Steam 库，进入 [b]steamapps/workshop/content/1972440/3833493529[/b]。
3. 双方各自在自己的电脑上双击 [b]Configure Steam Launch.vbs[/b]，选中平时玩游戏的 Steam 账号，点「应用并重启 Steam」。以后直接从 Steam 启动游戏即可。

[b]创建和加入房间[/b]
两台电脑需要能互相访问。在同一局域网里可以直接连接；异地游玩时，先加入同一个虚拟局域网，或由房主配置 TCP 内网穿透。双方进入「游玩」，选择同一种局域网模式。想玩王座，就都选「局域网合作」。

[b]房主（黑王）[/b]　如果有多个本地地址，先选朋友能连到的那个。点「创建房间」→「复制连接码」，把整段发给朋友。
[b]加入者（黑骑士）[/b]　复制连接码，点输入框右侧的「粘贴」，再点「加入」。连上后，由房主选武器和难度并开始游戏。

[b]用樱花 FRP 等穿透工具？[/b] 房主先把 TCP 隧道转发到大厅显示的本地地址和端口，再到「穿透设置（可选）」填入对外地址和端口，返回大厅创建房间。朋友照常用连接码加入。

